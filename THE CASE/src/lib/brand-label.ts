/**
 * Бренд товара для показа на витрине (C23). Чистый хелпер — тестируется без React.
 *
 * Витрина не имеет маршрута `/brands/[slug]` и фасета бренда в каталоге, поэтому
 * бренд рендерится ПЛЕЙН-ТЕКСТОМ (не ссылкой — иначе появился бы новый битый путь).
 * Условный показ (`null` при отсутствии бренда) делает функцию мультитенантной:
 * магазины без брендов/с одним брендом просто ничего не показывают.
 */

import type { StorefrontProduct } from "@/lib/admik";

export function brandLabel(p: Pick<StorefrontProduct, "brand">): string | null {
  return p.brand?.name ?? null;
}
