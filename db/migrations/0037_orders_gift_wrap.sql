-- 0037_orders_gift_wrap.sql  (правки владельца 2026-07-22, п.5)
--
-- orders.gift_wrap — покупатель попросил упаковать заказ в подарочную упаковку
-- (галочка в корзине). Признак нужен КОМПЛЕКТОВЩИКУ: без него заказ уезжает в
-- обычной упаковке, а покупатель ждёт подарочную.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ КОЛОНКА, А НЕ ТЕКСТ В orders.comment: комментарий — свободное
-- поле покупателя, его нельзя фильтровать, показывать колонкой в списке заказов
-- и на него нельзя навесить бизнес-логику (например, платную упаковку позже).
-- Булев флаг даёт админке честный признак вместо парсинга строки.
--
-- ОТЛИЧАЕТСЯ ОТ order_items.is_gift (0025): та колонка — про товар-ПОДАРОК,
-- выданный промокодом отдельной строкой заказа с нулевой ценой. Здесь — про
-- упаковку всего заказа. Разные сущности, поэтому разные поля.
--
-- Аддитивно и идемпотентно: ADD COLUMN IF NOT EXISTS + DEFAULT false покрывает
-- существующие строки без backfill; старый код о колонке не знает и продолжает
-- работать (§6.4/ADR-015).
--
-- Частичный индекс — только по заказам С упаковкой: их меньшинство, а выборка
-- «что упаковать» нужна складу регулярно.
--
-- GRANT не нужен: права на orders выданы целиком (0012) и распространяются на
-- новую колонку автоматически.
-- =============================================================================

ALTER TABLE orders
  ADD COLUMN IF NOT EXISTS gift_wrap boolean NOT NULL DEFAULT false;

CREATE INDEX IF NOT EXISTS orders_gift_wrap_idx ON orders (created_at DESC) WHERE gift_wrap;

COMMENT ON COLUMN orders.gift_wrap IS
  'Покупатель попросил подарочную упаковку заказа (галочка в корзине); '
  'не путать с order_items.is_gift — товаром-подарком по промокоду';

INSERT INTO schema_migrations (version, name)
VALUES ('0037', 'orders_gift_wrap')
ON CONFLICT DO NOTHING;
