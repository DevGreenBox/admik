-- только НЕТРОНУТУЮ строку и никогда не откатывает правки владельца из админки.
-- Повторный накат на уже отредактированную настройку — no-op.
--
-- КОНТРАКТ ЗНАЧЕНИЯ (lib/settings/schemas.ts, sizeChartsSchema): все ячейки —
-- СТРОКИ (не числа); ключи ячеек = column.key; id сеток уникальны; genders —
-- значения атрибута товара `gender`, витрина нормализует их (trim + lowercase +
-- ё→е) в selectSizeCharts (THE CASE/src/lib/size-table.ts).
